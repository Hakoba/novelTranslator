/**
 * Подсказка к иконочной кнопке. Контекстов два, и подсказка в них нужна разная.
 *
 * В оверлее на странице своя подсказка на CSS (`data-hint`, правило в `hints.css`):
 * Tooltip у PrimeVue рендерится в `document.body`, то есть вне shadow root, и остаётся
 * без стилей. Места там вдоволь — док шириной 380 px на всю страницу.
 *
 * В боковой панели браузера места нет: панель бывает уже 300 px, а подсказка прижата
 * к правому краю кнопки и растёт влево, поэтому у левых кнопок она упиралась в край
 * и обрезалась с обеих сторон. Нативный `title` рисует сам браузер — он не знает
 * границ страницы и обрезаться не может.
 *
 * Развилка идёт по сборке, а не по пропу: `OverlayHeader` и `WordItem` рендерятся
 * в Chrome только в панели, а в Firefox только в доке.
 */
export function hintAttrs(text: string): Record<string, string> {
  return __HAS_SIDE_PANEL__ ? { title: text } : { 'data-hint': text }
}
